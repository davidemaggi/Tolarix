package folder

import (
	"context"
	"errors"
	"fmt"
	"io/fs"
	"path"
	"strings"

	"github.com/davidemaggi/tolarix/core/internal/connectors"
	"github.com/davidemaggi/tolarix/core/internal/connectors/filetree"
	"github.com/davidemaggi/tolarix/core/internal/convert/frontmatter"
	"github.com/davidemaggi/tolarix/core/internal/model"
)

// GitHub wiki layout. GitHub shows every page at /wiki/<Page-Name> whatever
// folder its file is in, so page names are unique across the whole export
// and links use the name alone. A page's children go into a folder of the
// same name (only to keep the files tidy), _Sidebar.md shows the tree, and
// attachments go into _attachments, linked from the wiki root.
const (
	githubSidebar     = "_Sidebar.md"
	githubAttachments = "_attachments"
	// sidebarMarker starts a sidebar Tolarix wrote; one without it is never
	// overwritten.
	sidebarMarker = "<!-- Generated by Tolarix: edits here are replaced on the next run. -->"
)

// GitHub is the GitHub wiki Format.
type GitHub struct {
	root string
	nav  []navItem
}

type navItem struct {
	depth int
	title string
	name  string // page name; "" for a folder-only page
}

var _ filetree.Format = (*GitHub)(nil)

// githubNameReplacer drops what GitHub does not allow in page names (or
// what would break the page address), and turns spaces into "-".
var githubNameReplacer = strings.NewReplacer(
	`\`, "", "/", "", ":", "", "*", "", "?", "", `"`, "", "<", "", ">", "", "|", "", "#", "", "%", "", " ", "-",
)

// GitHubName is the file name (without .md) GitHub shows as title.
func GitHubName(title string) string {
	s := strings.Trim(githubNameReplacer.Replace(cleanTitle(title)), "._")
	if s == "" {
		s = "Untitled"
	}
	if filetree.WindowsReserved(s) {
		s += "_"
	}
	return s
}

func (g *GitHub) Hidden(rel string) bool {
	return filetree.DotHidden(rel) || rel == githubSidebar || rel == "_Footer.md" ||
		rel == githubAttachments || strings.HasPrefix(rel, githubAttachments+"/")
}

func (g *GitHub) Layout(tree *model.Tree, root string, w connectors.Warner) *connectors.Layout {
	g.root, g.nav = root, nil
	l := &connectors.Layout{Pages: map[string]connectors.Placement{}, Attachments: map[string]string{}}
	used := map[string]bool{}
	for _, r := range []string{"_Sidebar", "_Footer", githubAttachments, filetree.ArchiveFolder} {
		used[strings.ToLower(r)] = true
	}
	var place func(parentID, dir, parentKey string, depth int)
	place = func(parentID, dir, parentKey string, depth int) {
		for _, c := range tree.Children(parentID) {
			want := cleanTitle(filetree.FirstNonEmpty(c.Title, c.Name, "Untitled"))
			name := filetree.UniqueName(GitHubName(want), "-", used)
			if name != strings.ReplaceAll(want, " ", "-") {
				w.Warn(connectors.Warning{PageID: c.ID, Code: "renamed",
					Message: fmt.Sprintf("the page %q is saved as %q because GitHub does not allow some of its characters, or the name is already taken", c.Title, name)})
			}
			rel := filetree.JoinRel(dir, name)
			key, item := rel+".md", navItem{depth: depth, title: c.Title, name: name}
			if c.Placeholder {
				key, item.name = rel+"/", ""
			}
			g.nav = append(g.nav, item)
			l.Pages[c.ID] = connectors.Placement{Key: key, ParentKey: parentKey, Title: c.Title}
			place(c.ID, rel, key, depth+1)
		}
	}
	place("", root, "", 0)
	layoutAttachments(tree, l, filetree.JoinRel(root, githubAttachments))
	return l
}

func (g *GitHub) Encode(p *model.Page, l *connectors.Layout, w connectors.Warner) ([]byte, error) {
	fm, err := frontmatter.Block(p.Meta)
	if err != nil {
		return nil, fmt.Errorf("page %q: front matter: %w", p.ID, err)
	}
	body := encodeBody(p, l, w,
		func(key string) string { return escapePath(path.Base(filetree.TrimMD(key))) },
		// Page addresses are flat (/wiki/Name), so a path from the wiki root
		// works from every page.
		escapePath)
	return append(fm, body...), nil
}

// Finalize writes _Sidebar.md with the page tree, unless the folder has a
// sidebar someone else wrote.
func (g *GitHub) Finalize(ctx context.Context, t *filetree.Tree) error {
	key := filetree.JoinRel(g.root, githubSidebar)
	if _, exists := t.ID(key); exists {
		old, err := t.Read(ctx, key)
		if err != nil && !errors.Is(err, fs.ErrNotExist) {
			return err
		}
		if !strings.HasPrefix(string(old), sidebarMarker) {
			return nil
		}
	}
	if len(g.nav) == 0 {
		t.Delete(key)
		return nil
	}
	var b strings.Builder
	b.WriteString(sidebarMarker + "\n\n")
	for _, it := range g.nav {
		b.WriteString(strings.Repeat("  ", it.depth) + "- ")
		text := strings.NewReplacer("[", `\[`, "]", `\]`).Replace(it.title)
		if it.name == "" {
			b.WriteString(text + "\n")
			continue
		}
		b.WriteString("[" + text + "](" + escapePath(it.name) + ")\n")
	}
	t.Put(key, []byte(b.String()))
	return nil
}
